// Writes the logo's and the splash's drawn layers into assets/ui/brand/ from the design decision's
// own drawing (.scaffold/menus/design/splash/source/splash-canvas.mjs, option D, Lockup), so the
// program draws exactly what was chosen and nothing is redrawn by hand. Build time only, never
// shipped.
//
//   node tools/brand_art.mjs            write the layers
//   node tools/brand_art.mjs --check    compare them with what is committed; BRAND_ART_OK or exit 1
//
// THE NAME IS OUTLINES. The renderer's SVG library draws no text, so the carved name is shaped by
// HarfBuzz from the bundled title face (assets/fonts/title.ttf, Cinzel, OFL) through
// tools/outline_text.py and written as paths. The medallion is NOT here: it is the shipped layers
// in assets/ui/medallion/ with the mark's shader, composed by the stylesheet as everywhere else.
//
// Three files, one box (the lockup cropped to what it paints, in the splash's 960 by 620 space):
//   logo.svg          the slab, its grass and the name poured gold: the logo in the menus
//   splash-slab.svg   the same slab with the name carved and empty, before the gold
//   splash-gold.svg   the gold name alone, which the splash pours in from the left as it loads
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { lockupSlab } from "../.scaffold/menus/design/splash/source/splash-canvas.mjs";
import { plate, touchpad, SYMBOL } from "../.scaffold/menus/design/logo/source/logo-canvas.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const OUT = path.join(ROOT, "assets", "ui", "brand");

// The box the logo is cropped to, measured from what the lockup paints; the medallion's own box
// (290 by 276 at 30, 170) sits partly outside it, where it paints nothing.
export const BOX = [55, 200, 896, 237];

const run = { id: "name", font: path.join(ROOT, "assets", "fonts", "title.ttf"), axes: { wght: 800 },
  size: 50, text: "OoT: Recompiled", spacing: 5, x: 574, y: 330, anchor: "middle" };
const nm = JSON.parse(execFileSync("python", [path.join(HERE, "outline_text.py")], { input: JSON.stringify([run]) }).toString()).name;

const inner = s => s.replace(/^\s*<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const clean = s => s.replace(/\s(?:class|style|aria-hidden)="[^"]*"/g, "");
// A browser sizes a text's gradient to its line cell, so the outlines' gradients are pinned there.
const grad = (id, stops) => `<linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="0" y1="${nm.top}" x2="0" y2="${nm.bottom}">${stops}</linearGradient>`;
const CUT = grad("cutO", '<stop offset="0" stop-color="#0c1113"/><stop offset=".6" stop-color="#1b2326"/><stop offset="1" stop-color="#394447"/>');
const GOLD = grad("leafO", '<stop offset="0" stop-color="#fff2b8"/><stop offset=".45" stop-color="#e2bf4a"/><stop offset="1" stop-color="#9b7516"/>');
const carved = gold => `<g><path transform="translate(-1.2 -1.5)" d="${nm.d}" fill="#05080a" opacity=".85"/><path transform="translate(1 1.4)" d="${nm.d}" fill="#b6c0c2" opacity=".4"/><path d="${nm.d}" fill="url(#cutO)"/>${gold ? `<path d="${nm.d}" fill="url(#leafO)"/>` : ""}</g>`;
// The slab without its clip for the pour (the program pours by clipping an element instead).
const slab = gold => clean(inner(lockupSlab()))
  .replace(/<g font-family="Cinzel[\s\S]*?<\/g>/, carved(gold))
  .replace(/<clipPath id="pour">[\s\S]*?<\/clipPath>/, "")
  .replace("<defs>", `<defs>${CUT}${GOLD}`);
const doc = (what, body) => `<svg xmlns="http://www.w3.org/2000/svg" width="${BOX[2]}" height="${BOX[3]}" viewBox="${BOX.join(" ")}"><!-- ${what} Generated by tools/brand_art.mjs from the design decision; do not edit. -->${body}</svg>\n`;

// THE PROMPTS' PLATES (the user, 2026-10-12: "rounded gradient rectangles following same glossly
// look as the others with leaves too", and the touchpad "a trapezoid with the lower edge slightly
// smaller in width and rounded corners"): the drawing without its word, which the stylesheet sets
// over it in the program's own type. The face buttons' shapes are drawn white on the medallion's
// canvas, so the stylesheet tints each with its pastel (image-color).
const svgOf = (art, what) => art
  .replace(/<svg class="[^"]*" viewBox="0 0 (\d+) (\d+)"/, `<svg xmlns="http://www.w3.org/2000/svg" width="$1" height="$2" viewBox="0 0 $1 $2"`)
  .replace(/ aria-hidden="true">/, `><!-- ${what} Generated by tools/brand_art.mjs from the design canvas; do not edit. -->`)
  .replace(/<text[\s\S]*?<\/text>/, "") + "\n";
const symbol = (name, what) => `<svg xmlns="http://www.w3.org/2000/svg" width="200" height="190" viewBox="0 0 200 190"><!-- ${what} Generated by tools/brand_art.mjs; do not edit. -->${SYMBOL[name]("#ffffff")}</svg>\n`;

const FILES = {
  "logo.svg": doc("The logo's slab, grass and gold name; the medallion is drawn beside it from its own layers.", slab(true)),
  "splash-slab.svg": doc("The splash's slab with the name carved and empty.", slab(false)),
  "splash-gold.svg": doc("The gold name alone, poured in by the splash.", `<defs>${GOLD}</defs><path d="${nm.d}" fill="url(#leafO)"/>`),
};
// THE PLATE IN THREE (the user, 2026-10-13: the plates "need to actually expand and get a little bit
// wider" for longer words, "especially for like options, which ... overlaps the edges"). The renderer
// stretches an SVG to its box both ways, so a wider plate would stretch its leaves. The same drawing is
// cut into its two ends, drawn at their own width, and a middle that stretches with the word; the
// cuts fall where the rounded rectangle runs straight (x 88 and 176 of its 264).
const PLATE = svgOf(plate(""), "A word's plate: the medallion's gloss on a rounded rectangle, the leaves at its ends.");
const sliceOf = (x, w, what) => PLATE
  .replace('width="264" height="190" viewBox="0 0 264 190"', `width="${w}" height="190" viewBox="${x} 0 ${w} 190" preserveAspectRatio="none"`)
  .replace(/<!-- [\s\S]*? -->/, `<!-- ${what} Generated by tools/brand_art.mjs from the design canvas; do not edit. -->`);
const PROMPT_FILES = {
  "plate.svg": PLATE,
  "plate-left.svg": sliceOf(0, 88, "The plate's left end, its leaves and its rounded corner, held at its own width."),
  "plate-mid.svg": sliceOf(88, 88, "The plate's straight middle, which stretches with its word."),
  "plate-right.svg": sliceOf(176, 88, "The plate's right end, its leaves and its rounded corner, held at its own width."),
  "touchpad.svg": svgOf(touchpad(), "The touchpad: the plate's gloss on a rounded trapezoid, its lower edge narrower."),
  "cross.svg": symbol("cross", "A face button's cross, white, for the stylesheet to tint."),
  "circle.svg": symbol("circle", "A face button's circle, white, for the stylesheet to tint."),
  "square.svg": symbol("square", "A face button's square, white, for the stylesheet to tint."),
  "triangle.svg": symbol("triangle", "A face button's triangle, white, for the stylesheet to tint."),
};
// The pad prompts canvas is loaded only here, after the plate and the touchpad are drawn: its own sheets draw
// on import, and the drawings' ids are numbered in the order they are made, so loading it first would renumber
// the plate's and the touchpad's (both pinned by hash in assets/licenses/MANIFEST.txt).
const { sys, dpadInner, stickInner } = await import("../.scaffold/menus/design/prompts/source/pad-canvas.mjs");
// EVERY PAD BUTTON (the user, 2026-10-13: "Would ensure that the game ui has ui options for ALL buttons"; the pad
// prompts canvas, design-canvas://88118979-da17-473a-80af-d36cee03bfec, approved and finalized 12:47). The small
// buttons as whole drawings: the button's shape with its leaves over the left end of a stone, its word carved in gold
// (outlines, as the logo's name). Drawn on the plates' 190 high box, so the stylesheet sets them at the plates'
// height and their width follows. No maker's mark anywhere: every symbol is plain geometry, home is a house.
const SYSTEM = {
  view: ["round", "view", "VIEW", "View: a round button with two squares"],
  menu: ["round", "lines", "MENU", "Menu: a round button with three lines"],
  "share-bar": ["hpill", "share", "SHARE", "Share on the newer pads that have it: a flat bar with an arrow out of a tray"],
  guide: ["home", "house", "GUIDE", "Guide: the home button, a house"],
  create: ["vpill", "share", "CREATE", "Create: an upright pill with an arrow out of a tray"],
  options: ["vpill", "lines", "OPTIONS", "Options: an upright pill with three lines"],
  mute: ["hpill", "mic", "MUTE", "Mute: a flat pill with a microphone"],
  ps: ["home", "house", "PS", "PS: the home button, a house"],
  share: ["vpill", "share", "SHARE", "Share: an upright pill with an arrow out of a tray"],
  minus: ["round", "minus", "MINUS", "Minus: a small round button"],
  plus: ["round", "plus", "PLUS", "Plus: a small round button"],
  capture: ["square", "dot", "CAPTURE", "Capture: a rounded square with a dot"],
  home: ["home", "house", "HOME", "Home: the home button, a house"],
};
// The d-pad's arms and the sticks, drawn inside the program's own medallion (the stylesheet's layers, as a face
// button's shape is), in their own colors. Every set of lit arms, so any binding draws; a stick moving (every
// direction lit), in one direction, or pressed in.
const medalInner = (inner, what) => `<svg xmlns="http://www.w3.org/2000/svg" width="200" height="190" viewBox="0 0 200 190"><!-- ${what} Generated by tools/brand_art.mjs from the design canvas; do not edit. -->${inner}</svg>\n`;
const DIRS = ["up", "down", "left", "right"];
const DPAD = {};
for (let mask = 1; mask < 16; ++mask) {
  const lit = DIRS.filter((_, i) => mask & (1 << i));
  DPAD[`dpad-${lit.join("-")}.svg`] = medalInner(dpadInner(...lit), `The d-pad's four arms, ${lit.join(" and ")} lit.`);
}
const STICKS = {};
for (const [letter, name] of [["L", "l"], ["R", "r"]]) {
  STICKS[`stick-${name}.svg`] = medalInner(stickInner(letter, DIRS, false, true), `The ${letter} stick, moving every way.`);
  for (const d of DIRS) STICKS[`stick-${name}-${d}.svg`] = medalInner(stickInner(letter, [d], false, true), `The ${letter} stick, ${d}.`);
  STICKS[`stick-${name}-press.svg`] = medalInner(stickInner(letter, [], true, true), `The ${letter} stick, pressed in.`);
}
for (const [name, [shape, mark, word, what]] of Object.entries(SYSTEM)) {
  PROMPT_FILES[`sys-${name}.svg`] = svgOf(sys(shape, mark, word), `${what}, its word carved on stone.`);
}
Object.assign(PROMPT_FILES, DPAD, STICKS);
const PROMPTS = path.join(ROOT, "assets", "ui", "prompts");

const ALL = [...Object.entries(FILES).map(([n, t]) => [path.join(OUT, n), t]),
             ...Object.entries(PROMPT_FILES).map(([n, t]) => [path.join(PROMPTS, n), t])];
if (process.argv.includes("--check")) {
  const stale = ALL.filter(([file, text]) =>
    !existsSync(file) || readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== text).map(([file]) => path.relative(ROOT, file));
  if (stale.length) {
    console.log(`BRAND_ART_FAIL ${stale.join(", ")} differ from the decision's drawing; run node tools/brand_art.mjs`);
    process.exit(1);
  }
  console.log(`BRAND_ART_OK ${ALL.length} files`);
}
else {
  mkdirSync(OUT, { recursive: true });
  mkdirSync(PROMPTS, { recursive: true });
  for (const [file, text] of ALL) writeFileSync(file, text);
  console.log(`wrote ${ALL.length} files to assets/ui/brand and assets/ui/prompts`);
}
