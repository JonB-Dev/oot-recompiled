"""Write the interface's tokens as a C++ header, so native code never copies a value by hand.

The installer (src/setup/setup.cpp) draws its own window with GDI and used to carry the palette as
literals typed in from the token file, which is how it drifted; the input layer needs the repeat
timing the tokens set. Both read this header instead. Every custom property in tokens.rcss whose
value resolves (through var() references) to a color, a length in dp, a duration, a plain number or
a font family becomes a constant:

    --color-slate-deep: #0c1215;   ->  inline constexpr uint32_t color_slate_deep = 0x0c1215ffu;  // RGBA
    --space-4: 16dp;               ->  inline constexpr float space_4 = 16.0f;                      // dp
    --repeat-delay: 0.38s;         ->  inline constexpr float repeat_delay = 0.38f;                 // seconds

    python tools/tokens_header.py <out.h>            write it (CMake does, on every token change)
    python tools/tokens_header.py --check <out.h>    fail if the file differs from a fresh write
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOKENS = os.path.join(ROOT, "assets", "ui", "tokens.rcss")

DECL = re.compile(r"^\s*--([a-z0-9-]+)\s*:\s*([^;]+);", re.MULTILINE)
VAR = re.compile(r"^var\(--([a-z0-9-]+)\)$")


def tokens():
    text = re.sub(r"/\*.*?\*/", "", open(TOKENS, encoding="utf-8").read(), flags=re.DOTALL)
    # The first definition of each token is its value: a later block that gives some again for a
    # class (.prompts-full-size, in px) is an override for the stylesheets, not the token itself.
    table = {}
    for name, value in DECL.findall(text):
        table.setdefault(name, value.strip())
    return table


def resolve(name, table, seen=()):
    value = table[name]
    m = VAR.match(value)
    if not m:
        return value
    if m.group(1) in seen or m.group(1) not in table:
        raise ValueError("--%s cannot be resolved" % name)
    return resolve(m.group(1), table, seen + (name,))


def constant(name, value):
    ident = name.replace("-", "_")
    m = re.fullmatch(r"#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?", value)
    if m:
        rgba = m.group(1).lower() + (m.group(2) or "ff").lower()
        return "inline constexpr uint32_t %s = 0x%su;  // RGBA" % (ident, rgba)
    m = re.fullmatch(r"(-?\d+(?:\.\d+)?)dp", value)
    if m:
        return "inline constexpr float %s = %sf;  // dp" % (ident, float(m.group(1)))
    m = re.fullmatch(r"(\d+(?:\.\d+)?)s", value)
    if m:
        return "inline constexpr float %s = %sf;  // seconds" % (ident, float(m.group(1)))
    m = re.fullmatch(r"-?\d+(?:\.\d+)?", value)
    if m:
        return "inline constexpr float %s = %sf;" % (ident, float(value))
    if name.startswith("font-"):
        return 'inline constexpr const char* %s = "%s";' % (ident, value)
    return None   # a keyword, a percentage or an em: nothing native reads those


def header():
    table = tokens()
    lines = [
        "// GENERATED by tools/tokens_header.py from assets/ui/tokens.rcss. Do not edit: change the",
        "// token and rebuild. The same values the stylesheets use, for native code.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace oot::ui::tokens {",
        "",
    ]
    for name in table:
        out = constant(name, resolve(name, table))
        if out:
            lines.append("    " + out)
    lines += ["", "}", ""]
    return "\n".join(lines)


def main(argv):
    check = "--check" in argv
    paths = [a for a in argv if not a.startswith("--")]
    if not paths:
        print("usage: tokens_header.py [--check] <out.h>")
        return 2
    text = header()
    if check:
        ok = os.path.exists(paths[0]) and open(paths[0], encoding="utf-8").read() == text
        print("TOKENS_HEADER_OK" if ok else "TOKENS_HEADER_FAIL %s differs from a fresh write" % paths[0])
        return 0 if ok else 1
    os.makedirs(os.path.dirname(os.path.abspath(paths[0])), exist_ok=True)
    old = open(paths[0], encoding="utf-8").read() if os.path.exists(paths[0]) else None
    if old != text:
        with open(paths[0], "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
